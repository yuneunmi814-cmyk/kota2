/**
 * 축제 하나의 테마 목록. 이름 + 요약 첫 문장 + (있으면) 문체부 유형으로 판정.
 * 어디에도 안 걸리면 빈 배열 — 억지로 채우지 않는다(잘못된 분류가 없느니만 못함).
 *
 * 키워드를 산문 전체에 걸면 안 된다. kfes 개요가 400자짜리 산문이 되면서 부수적 언급까지
 * 다 잡혔다 — 통영한산대첩에 '바다'(nature)·'공연'(music)·'체험'(family)이 붙어 테마가 5개가
 * 됐고, 6개 중 4개 이상 붙은 축제가 111건(16%)이었다. 그러면 필터가 아무것도 걸러내지 못한다.
 * 축제의 정체는 이름과 첫 문장에 있다("무주반딧불축제는 …반딧불이와 청정 자연환경을 테마로 한
 * 대한민국 대표 환경축제이다").
 */
const identity = (summary?: string | null) => {
  if (!summary) return ''
  const m = summary.match(/^[^.。!?\n]{0,160}[.。!?]?/)
  return m ? m[0] : summary.slice(0, 160)
}

export function classifyThemes(name: string, summary?: string | null): Theme[] {
  const found = new Set<Theme>()

  // ① 문체부 공식 유형 — '· 문화예술' 같은 구조화된 태그라 산문과 달리 안전하다
  for (const [re, themes] of OFFICIAL) {
    if (summary && re.test(summary)) themes.forEach((t) => found.add(t))
  }

  // ② 이름 — 축제의 정체는 이름에 있다. 여기서 뭐라도 나오면 그걸로 끝낸다.
  const fromName = new Set<Theme>()
  for (const [re, themes] of KEYWORDS) {
    if (re.test(name)) themes.forEach((t) => fromName.add(t))
  }
  if (fromName.size > 0) {
    fromName.forEach((t) => found.add(t))
    return THEMES.filter((t) => found.has(t))
  }

  // ③ 이름이 비었을 때만 요약 첫 문장을 보조로 — 부수적 언급까지 잡히므로 최후수단이다.
  //    ('강릉 국가유산 야행'은 이름만으로 heritage·night가 나오니 소개문의 '자연'·'공연'을 볼 이유가 없다)
  const head = identity(summary)
  for (const [re, themes] of KEYWORDS) {
    if (head && re.test(head)) themes.forEach((t) => found.add(t))
  }
  return THEMES.filter((t) => found.has(t)) // 항상 같은 순서로
}
