// 주소에 쓰는 축제 식별자.
//
// externalId는 `tourapi:506895`처럼 콜론이 들어 있다. 이걸 그대로 주소에 두면
// 카카오톡 공유가 통째로 죽는다 — 카카오 스크래퍼가 경로 안의 콜론을 보고
// "Invalid URL"로 거부한다(카카오 공유 디버거로 확인, 2026-08-18).
// 목록 페이지(`/ko/festivals/`)는 멀쩡히 긁히는데 상세만 막혔던 이유가 이것이다.
// 하필 사람들이 공유하는 건 전부 상세 페이지다.
//
// 축제는 "같이 갈래?"로 퍼지는 물건이라 공유가 막히는 건 기능 하나가 빠진 게 아니라
// 유입 경로가 끊긴 것이다. 그래서 주소에서만 첫 콜론을 하이픈으로 바꾼다.
//
// DB의 id는 건드리지 않는다 — 이미 쌓인 리뷰·행동로그가 전부 그 id를 가리킨다.
//
// 되돌릴 때 '첫' 하이픈만 바꾸는 게 중요하다. 뒤쪽 하이픈은 id 본문이다
// (예: `stdfest:2025년인천도시역사관어린이특별전-2025-12-09`).
// 소스 이름(tourapi·kfes·stdfest·manual)에는 하이픈이 없어서 이 규칙이 성립한다.
//
// 이 파일은 클라이언트 컴포넌트에서도 import 하므로 서버 전용 모듈(supabase 등)을
// 끌어오지 않는다.

export const toSlug = (externalId: string) => externalId.replace(':', '-')

// 주소에서 받은 값을 DB의 id로 되돌린다.
//
// 콜론이 이미 있으면 옛 주소다 — 그대로 쓴다. 오늘 이전에 공유된 링크와 카카오가
// 캐시해 둔 항목이 그 형태이고, 그걸 404로 만들면 이미 나간 링크가 전부 죽는다.
// 새 주소는 콜론이 없으니 첫 하이픈을 콜론으로 되돌린다.
//
// 옛 주소도 열리지만 페이지의 canonical은 항상 새 주소를 가리킨다 —
// 검색엔진은 그걸 보고 하나로 합친다.
// 소스 이름은 이 넷뿐이다. 앞에서부터 맞춰 보는 이유는 아래 사고 때문이다.
const SOURCES = ['tourapi', 'kfes', 'stdfest', 'manual'] as const

export const fromSlug = (slug: string) => {
  // 소스 이름으로 시작하면 그 뒤 첫 글자만 보면 된다.
  //
  // 전에는 '콜론이 들어 있으면 옛 주소'로 판단했다. 그런데 축제 **이름 자체에** 콜론이 든
  // 것이 있었다 — `원도심골목길축제<여름:성안이즈백>`. 새 주소인데도 콜론이 보이니 옛 주소로
  // 오해해 그대로 돌려줬고, 그 값은 DB의 id(`stdfest:원도심…`)와 달라 조회에 실패해 404가 났다.
  // 목록에는 떠 있는데 누르면 없는 페이지가 나왔다(2026-08-23 영어 화면 점검에서 2건 발견).
  for (const src of SOURCES) {
    if (slug.startsWith(`${src}:`)) return slug                       // 옛 주소 — 그대로
    if (slug.startsWith(`${src}-`)) return `${src}:${slug.slice(src.length + 1)}`
  }
  // 알 수 없는 접두사 — 예전 규칙으로 떨어뜨린다
  return slug.includes(':') ? slug : slug.replace('-', ':')
}
